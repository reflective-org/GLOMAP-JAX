def test_nothing_in_the_vendored_tree_assigns_coag_mode():
    """The setup-independence claim, made against the source text.

    Every mention of the name in `fortran/src/` must be the one declaration,
    the two lines of the single consumer, a `USE ... ONLY` import, or a
    comment. An assignment anywhere else would mean the table is configuration
    after all. Fails if a future vendored update adds one.
    """
    hits = []
    for path in sorted((REPO / "fortran" / "src").rglob("*.F90")):
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if "coag_mode" in line:
                hits.append((path.name, lineno, line.strip()))

    code = [h for h in hits if not h[2].startswith("!")]
    declarations = [h for h in code if "PARAMETER" in h[2]]
    assert len(declarations) == 1, declarations
    assert declarations[0][0] == "ukca_mode_setup.F90"
    assert declarations[0][1] == 174

    consumers = {(h[0], h[1]) for h in code} - {(h[0], h[1]) for h in declarations}
    # The RESHAPE literal spans continuation lines that do not repeat the name,
    # so the only remaining code lines are the USE and the single call site.
    assert consumers == {
        ("ukca_coagwithnucl.F90", 152),  # USE ukca_mode_setup, ONLY: ... coag_mode
        ("ukca_coagwithnucl.F90", 534),  # mtrantoi(:,coag_mode(imode,jmode),icp) =
        ("ukca_coagwithnucl.F90", 535),  #      mtrantoi(:,coag_mode(imode,jmode),icp) +
    }, sorted(consumers)


