def test_accumulation_order_is_the_fortran_loop_order():
    """`imode` outer then `jmode`, and every source pair accounted for exactly
    once. Fails if `accumulation_order` stops sorting."""
    for setup in SETUPS:
        tables = modes.build(setup, l_dust_mp_ageing=True)
        plan = accumulation_order(tables)
        flat = [pair for pairs in plan.values() for pair in pairs]
        assert sorted(flat) == sorted(source_pairs(tables))
        for dest, pairs in plan.items():
            assert list(pairs) == sorted(pairs), (setup, dest)
            assert all(destination(i, j) == dest for i, j in pairs)


def test_the_accumulation_order_is_not_an_academic_concern():
    """The float-associativity claim, measured rather than asserted.

    Eight terms into one destination is what setup 8 with dust ageing produces.
    Summed in Fortran order and in reverse they give two different doubles, so
    a `.at[].add()` whose order XLA chooses is a different answer, not a
    differently-spelled one. Fails only if float64 addition becomes
    associative.
    """
    terms = jnp.array([1.0, 1e-16, 1e-16, 1e-16, 1e-16, 1e-16, 1e-16, 1e-16], dtype=jnp.float64)

    forward = jnp.zeros((), dtype=jnp.float64)
    for term in terms:
        forward = forward + term
    backward = jnp.zeros((), dtype=jnp.float64)
    for term in terms[::-1]:
        backward = backward + term

    assert float(forward) != float(backward)
    # And the same through the mechanism the port will actually use.
    acc_f = jnp.zeros(1, dtype=jnp.float64)
    for term in terms:
        acc_f = acc_f.at[0].add(term)
    acc_b = jnp.zeros(1, dtype=jnp.float64)
    for term in terms[::-1]:
        acc_b = acc_b.at[0].add(term)
    assert float(acc_f[0]) != float(acc_b[0])


