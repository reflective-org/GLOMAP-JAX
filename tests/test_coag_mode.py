def _setup_of(namelist: Path) -> int:
    text = namelist.read_text(encoding="utf-8")
    found = re.findall(r"^\s*i_mode_setup\s*=\s*(\d+)", text, flags=re.MULTILINE)
    assert len(found) == 1, f"{namelist.name}: {len(found)} i_mode_setup lines"
    # The switches that would change `topmode` or the active modes are not
    # overridden in any shipped namelist, so modes.build's defaults apply. If
    # one ever is, this assertion is where it surfaces rather than as a silently
    # wrong pair list.
    for switch in ("l_dust_mp_ageing", "l_radaer", "i_tune_bc"):
        assert switch not in text, f"{namelist.name} overrides {switch}"
    return int(found[0])


@pytest.mark.parametrize("case", sorted(CASES))
def test_source_pairs_match_the_committed_branch_goldens(case):
    """`source_pairs` reimplements `ukca_coagwithnucl`'s loop nest, and the
    branch dump recorded which `(imode, jmode)` the Fortran actually visited.

    This is the check that the loop bounds are right. Fails on an off-by-one in
    any of the three blocks — mutate `imode + 4` to `imode + 3` and
    `marine_bcoc` reports a pair the Fortran never visited.
    """
    archive = REPO / "tests" / "goldens" / f"{case}.f64.branches.npz"
    with np.load(archive, allow_pickle=False) as data:
        sites = [str(s) for s in data["site_levels"]]
        wanted = {sites.index(s) for s in PAIR_SITES if s in sites}
        keep = np.isin(data["site"], list(wanted))
        recorded = {(int(a) - 1, int(b) - 1) for a, b in zip(data["i1"][keep], data["i2"][keep])}

    tables = modes.build(_setup_of(CASES[case]))
    assert recorded == set(source_pairs(tables))


