def test_a_single_changed_digit_in_the_source_moves_the_parse(source_text):
    """The mutation test for the two above. Without it they could both be
    passing on a parser that returns a constant.

    Flips the last entry of the first RESHAPE line, 4 -> 5, and checks the
    parse follows it in exactly one place.
    """
    mutated, n = re.subn(
        r"(1, 2, 3, 4, 2, 3, )4, 4,",
        r"\g<1>4, 5,",
        source_text,
        count=1,
    )
    assert n == 1, "the mutation did not apply -- this test proves nothing as written"

    moved = capture.parse_source(mutated)
    differing = np.argwhere(moved != COAG_MODE_FORTRAN)
    assert differing.shape[0] == 1, f"expected 1 changed entry, got {differing.shape[0]}"
    # Source line 1 is coag_mode(1:8, 1), so entry 8 of it is coag_mode(8, 1).
    assert tuple(differing[0]) == (7, 0)
    with pytest.raises(AssertionError):
        np.testing.assert_array_equal(COAG_MODE_FORTRAN, moved)


def test_the_parser_refuses_a_source_with_no_declaration(source_text):
    """A regex that silently matches nothing is how the wrong golden ships."""
