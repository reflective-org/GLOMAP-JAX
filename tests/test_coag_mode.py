def test_the_capture_actually_varied_the_setup(golden):
    """The anti-tautology guard.

    `coag_mode` being identical across setups is only evidence if the setups
    were actually different. The archive carries `mode`, `topmode` and `ncp`
    per setup for exactly this reason. Fails if the capture script's namelist
    replacement ever no-ops and every subprocess runs setup 1 — the failure
    mode this repo has already shipped once.
    """
    witnesses = {
        setup: (
            tuple(int(v) for v in golden[f"s{setup}_mode"]),
            int(golden[f"s{setup}_topmode"]),
            int(golden[f"s{setup}_ncp"]),
        )
        for setup in SETUPS
    }
    assert len(set(witnesses.values())) > 1, witnesses
    # Four distinct active-mode patterns across the seven setups.
    assert len({w[0] for w in witnesses.values()}) == 4
    active = {setup: sum(w[0]) for setup, w in witnesses.items()}
    assert active == {1: 4, 2: 5, 3: 4, 4: 5, 5: 4, 6: 2, 8: 7}


