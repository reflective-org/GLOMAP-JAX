def test_the_zero_based_and_one_based_tables_agree():
    np.testing.assert_array_equal(COAG_MODE, COAG_MODE_FORTRAN - 1)
    assert COAG_MODE.min() == 0
    assert COAG_MODE.max() == modes.NMODES - 1


def test_the_tables_are_read_only():
    """They are module-level shared state. A caller that mutated one in place
    would change every later import in the process."""
    for table in (COAG_MODE, COAG_MODE_FORTRAN):
        with pytest.raises(ValueError):
            table[0, 0] = 99


def test_the_table_is_symmetric_which_is_why_no_test_can_catch_a_transpose():
    """Stated as a test so the limitation is recorded rather than assumed.

    `coag_mode(i,j) == coag_mode(j,i)` for all 64 entries, so a transposed
    transcription is byte-equal to the correct one and neither the source
    re-parse nor the f2py capture could distinguish them. If this ever fails,
    the port has gained a real check it did not have before — and every
    `(imode, jmode)` order in `coag_mode.py` needs re-deriving from the call
    site, because it was never pinned by data.
    """
    np.testing.assert_array_equal(COAG_MODE, COAG_MODE.T)


def test_the_diagonal_is_the_identity():
    """Intra-modal coagulation keeps its mass in the same mode. Not exercised
    by the scatter — `mtran(:,:,i,i)` is never written — but a table whose
    diagonal moved would mean the whole reading of it is wrong."""
    np.testing.assert_array_equal(np.diag(COAG_MODE), np.arange(modes.NMODES))


def test_the_full_table_census_is_what_the_docstring_says():
    """The number quoted in `coag_mode.py`, recomputed from committed data."""
    assert full_table_census() == {0: 1, 1: 7, 2: 13, 3: 27, 4: 1, 5: 3, 6: 5, 7: 7}
    assert sum(full_table_census().values()) == modes.NMODES**2


def test_destination_reads_the_call_sites_subscript_order():
    """`coag_mode(imode, jmode)` with `imode` the mode losing the mass."""
    assert destination(0, 4) == COAG_MODE[0, 4]
    # Nuc-sol coagulating with Ait-insol lands in Ait-sol (Fortran 1,5 -> 2).
    assert destination(0, 4) == 1
    # Anything with Cor-sol lands in Cor-sol.
    assert all(destination(i, 3) == 3 for i in range(modes.NMODES))


